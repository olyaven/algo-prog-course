double celsius = 50.0;

const double Fahrenheit1 = 9.0 / 5.0;
const double Fahrenheit2 = 32.0;
const double Kelvin1 = 273.15;

double fahrenheit = celsius * Fahrenheit1 + Fahrenheit2;
double kelvin = celsius + Kelvin1;

Console.WriteLine($"{celsius}°C = {fahrenheit}°F = {kelvin}K");
Console.WriteLine($"Сишарп ощущается очень неудобным и громостким после питона, что грустно. но логика очень похожая, так что нужно просто выучить синтаксисы");